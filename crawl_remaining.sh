#!/bin/bash

# ======================================================================
# 나머지 지역 자동 크롤링 쉘 스크립트
# 제외 지역: 서울, 광주, 부산, 전남, 전북 (이미 데이터 존재)
# 대상 지역: 대구, 인천, 대전, 울산, 세종, 경기, 강원, 충북, 충남, 경북, 경남, 제주
# ======================================================================

REGIONS=("대전" "울산" "세종" "경기" "강원" "충북" "충남" "경북" "경남" "제주")

echo "[START] 나머지 ${#REGIONS[@]}개 지역에 대한 자동 크롤링을 시작합니다."
echo "대상 지역: ${REGIONS[*]}"
echo ""

for REGION in "${REGIONS[@]}"; do
    echo "============================================================"
    echo "[$REGION] 지역 크롤링 시작 시간: $(date '+%Y-%m-%d %H:%M:%S')"
    echo "============================================================"
    
    python auto_crawling.py --region "$REGION"
    
    if [ $? -eq 0 ]; then
        echo "[SUCCESS] $REGION 지역 크롤링이 완료되었습니다."
    else
        echo "[ERROR] $REGION 지역 크롤링 중 오류가 발생했습니다."
    fi
    echo ""
done

echo "============================================================"
echo "[FINISH] 모든 지역에 대한 크롤링 작업이 종료되었습니다."
echo "============================================================"
